// Texts that contain numbers or names are matched with patterns.
const PATTERNS = [
  [/^(\d+) subject tumhare naam par hai\. Class shuru karo aur QR dikhao\.$/, '$1 subject(s) assigned to you. Start a class and show the QR code.'],
  [/^(\d+) \/ (\d+) class attend ki$/, '$1 / $2 classes attended'],
  [/^75% tak pahunchne ke liye lagatar (\d+) class aur attend karni hogi\.$/, 'You need to attend $1 more classes in a row to reach 75%.'],
  [/^Sab theek hai\. 75% se upar rehte hue tum (\d+) class tak chhod sakte ho\.$/, 'All good. You can miss up to $1 classes and stay above 75%.'],
  [/^Abhi ka email: (.*)\. Jo badalna hai wahi bharo, baaki khali chhod do\.$/, 'Current email: $1. Fill in only what you want to change and leave the rest empty.'],
  [/^(Student|Teacher) "(.*)" ko delete karna hai\?$/, 'Delete $1 "$2"?'],
  [/^Subject "(.*)" ko delete karna hai\?$/, 'Delete subject "$1"?'],
  [/^(Student|Teacher) delete ho gaya$/, '$1 deleted'],
  [/^OTP (.+) par bhej diya gaya hai$/, 'OTP sent to $1'],
  [/^(.*) baje$/, '$1'],
  [/^Is class me roll number (\d+) pehle se kisi aur student ka hai$/, 'Roll number $1 already belongs to another student in this class'],
  [/^Roll number 1 se (\d+) ke beech ka poora number (?:hona chahiye|ho)$/, 'Roll number must be a whole number between 1 and $1'],
  [/^(Roll number|Roll) 1 se (\d+) ke beech hona chahiye$/, 'Roll number must be between 1 and $2'],
];

const isSingleWord = (key) => key.trim().indexOf(' ') === -1;

export function toEnglish(text) {
  if (!text || !/[A-Za-z]/.test(text)) return text;
  const trimmed = text.trim();
  for (let i = 0; i < PATTERNS.length; i += 1) {
    const rule = PATTERNS[i];
    if (rule[0].test(trimmed)) {
      return text.replace(trimmed, trimmed.replace(rule[0], rule[1]));
    }
  }
  let out = text;
  for (let i = 0; i < PAIRS.length; i += 1) {
    const key = PAIRS[i][0];
    const value = PAIRS[i][1];
    if (isSingleWord(key)) {
      if (out.trim() === key.trim()) out = out.replace(key.trim(), value);
    } else if (out.indexOf(key) !== -1) {
      out = out.split(key).join(value);
    }
  }
  return out;
}